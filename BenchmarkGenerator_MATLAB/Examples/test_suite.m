%% Helper function for plotting
function ask_and_plot(PORTAL, test_name)
    fprintf('\n[%s] completed.\n', test_name);
    response = input('Plot this instance? (y/n): ', 's');
    if strcmpi(response, 'y')
        Playground_MATLAB_Script(PORTAL, 200, true);
        fprintf('Plotting complete. Close figures to continue.\n');
        pause;  % Wait for user to close figures
    end
    fprintf('\n');
end

