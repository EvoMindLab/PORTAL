test_points = randn(2, 10);
fitness_match = true;

for i = 1:10
    x = test_points(:, i);
    f_export = fitness(x, PORTAL_export);
    f_import = fitness(x, PORTAL_import);

    if abs(f_export - f_import) > 1e-10
        fprintf('✗ Fitness mismatch at point %d: %.10f vs %.10f\n', i, f_export, f_import);
        fitness_match = false;
    end
end

