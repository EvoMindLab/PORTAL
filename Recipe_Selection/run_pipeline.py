"""
run_pipeline.py
===============
Run the PORTAL raw Performance / ELA data-collection pipeline in order:

    1. run_ela.py              -> results/ela_portal_anchors.csv
    2. run_curation_solvers.py -> results/performance_raw_portal_anchors.csv

This convenience script produces two raw tables and a combined metadata note:

    * results/ela_portal_anchors.csv        — raw ELA feature table
    * results/performance_raw_portal_anchors.csv    — raw run-level Performance table
    * results/PORTAL_performance_ELA_metadata.md    — combined metadata note

All measurements use Type 0 (no realization) on the full recipe Suite.
For configurable end-to-end curation, use the repository-root
``run_suite_pipeline.py`` entry point instead.

Usage:
    python run_pipeline.py
    python run_pipeline.py --force
    python run_pipeline.py --from performance
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import time
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
ROOT = SCRIPT_DIR.parent  # project root (one level up from Recipe_Selection/)
RESULTS = ROOT / 'results'

STAGES = [
    {
        'key': 'ela',
        'name': 'ELA raw feature extraction on all recipes',
        'script': SCRIPT_DIR / 'run_ela.py',
        'output': RESULTS / 'ela_portal_anchors.csv',
        'metadata': RESULTS / 'ela_metadata.md',
    },
    {
        'key': 'performance',
        'name': 'Performance raw data collection on all recipes',
        'script': SCRIPT_DIR / 'run_curation_solvers.py',
        'output': RESULTS / 'performance_raw_portal_anchors.csv',
        'metadata': RESULTS / 'performance_metadata.md',
    },
]

# Consolidated measurement metadata note (ELA + Performance settings in one file).
METADATA_NOTE = RESULTS / 'PORTAL_performance_ELA_metadata.md'


def write_combined_metadata():
    """Merge the per-stage metadata notes into one measurement metadata file."""
    parts = []
    for stage in STAGES:
        md = stage.get('metadata')
        if md is not None and md.exists():
            parts.append(md.read_text(encoding='utf-8').strip())
    if not parts:
        return None
    header = (
        '# PORTAL Performance / ELA Raw Data-Collection — Metadata Note\n\n'
        'This note records the exact Performance and ELA settings used to produce\n'
        'the raw deliverables. Auto-generated by run_pipeline.py.\n'
    )
    METADATA_NOTE.parent.mkdir(parents=True, exist_ok=True)
    METADATA_NOTE.write_text(
        header + '\n\n---\n\n'.join(parts) + '\n', encoding='utf-8'
    )
    return METADATA_NOTE


def run_stage(stage):
    print(f"\n{'=' * 70}")
    print(f"  Stage: {stage['name']}")
    print(f"  Script: {stage['script'].name}")
    print(f"{'=' * 70}\n", flush=True)

    t_start = time.time()
    result = subprocess.run([sys.executable, str(stage['script'])], cwd=SCRIPT_DIR)
    elapsed = time.time() - t_start

    if result.returncode != 0:
        print(f"\nStage '{stage['key']}' failed with exit code {result.returncode}")
        print(f"Time elapsed: {elapsed / 60:.1f} min")
        sys.exit(result.returncode)

    print(f"\nStage '{stage['key']}' done in {elapsed / 60:.1f} min")


def main():
    parser = argparse.ArgumentParser(description='Run PORTAL2 ELA+Performance pipeline.')
    parser.add_argument(
        '--force',
        action='store_true',
        help='Rerun all stages even if outputs exist.',
    )
    parser.add_argument(
        '--from',
        dest='start_from',
        choices=['ela', 'performance'],
        default=None,
        help='Start from a specific stage (skip earlier stages).',
    )
    args = parser.parse_args()

    print('=' * 70)
    print('PORTAL2 Pipeline — ELA + Performance (Anchor-Based)')
    print('=' * 70)
    print(f'Working directory: {SCRIPT_DIR}')
    print(f'Results directory: {RESULTS}')

    if args.start_from is not None:
        start_idx = next(i for i, s in enumerate(STAGES) if s['key'] == args.start_from)
        plan = STAGES[start_idx:]
        print(f"Mode: starting from '{args.start_from}'")
    elif args.force:
        plan = STAGES
        print('Mode: --force (rerun all stages)')
    else:
        plan = []
        for stage in STAGES:
            if stage['output'].exists():
                print(f"  Skip '{stage['key']}' — output exists: {stage['output'].name}")
            else:
                plan.append(stage)
        if not plan:
            print('\nAll outputs already exist. Use --force to rerun.')
            return

    print(f"\nStages to run: {[s['key'] for s in plan]}")

    t_total = time.time()
    for stage in plan:
        run_stage(stage)
        if not stage['output'].exists():
            print(f"\nStage '{stage['key']}' finished but did not produce {stage['output']}")
            sys.exit(1)

    elapsed = time.time() - t_total

    note = write_combined_metadata()

    print(f"\n{'=' * 70}")
    print(f'PIPELINE COMPLETE in {elapsed / 60:.1f} min')
    print(f"{'=' * 70}")
    print('Deliverables in results/:')
    for stage in STAGES:
        marker = 'OK' if stage['output'].exists() else 'MISSING'
        print(f"  {marker} {stage['output'].name}")
    if note is not None and note.exists():
        print(f"  OK {note.name}")
    else:
        print(f"  MISSING {METADATA_NOTE.name}")


if __name__ == '__main__':
    main()
